export type LessonWorldAssignment = {
  lessonNumber: number;
  themeId: ItalianWorldId;
  sceneId: ItalianWorldId;
  characterId: WorldCharacterId;
  interactiveProps: readonly string[];
  completionEffect: string;
  educationalVisuals: readonly string[];
};

export const publishedLessonWorldAssignments: readonly LessonWorldAssignment[] =
  publishedLessonWorldIds.map((sceneId, index) => {
    const world = worldById[sceneId];
    return {
      lessonNumber: index + 1,
      themeId: sceneId,
      sceneId,
      characterId: world.characterId,
      interactiveProps: [world.interactiveProp],
      completionEffect:
        index === 49 || index === 79 ? "festival-stamp" : "approved-stamp",
      educationalVisuals: [world.scenery[0], world.scenery[1]],
    };
  });

export function worldForLesson(
  number: number,
): (typeof italianWorlds)[number] | null {
  const assignment = publishedLessonWorldAssignments[number - 1];
  return assignment?.lessonNumber === number
    ? worldById[assignment.sceneId]
    : null;
}

export const worldStops = Array.from({ length: 15 }, (_, index) => ({
  id: index + 1,
  firstLesson: index * 10 + 1,
  lastLesson: (index + 1) * 10,
  worldId: publishedLessonWorldIds[index * 10] ?? null,
  published: index < 8,
}));
