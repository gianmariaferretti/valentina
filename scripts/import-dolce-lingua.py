"""Import the four supplied Word manuals without editing their prose.

Usage: python scripts/import-dolce-lingua.py [--verify] volume1.docx ... volume4.docx
The output contains every non-empty lesson paragraph in document order. The
source checksum and paragraph count make future imports auditable.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

from docx import Document


ROOT = Path(__file__).resolve().parents[1] / "src/content/italian/original-lessons"
LESSONS = ROOT / "lessons"
IMPORTS = Path(__file__).resolve().parents[1] / "src/features/italian-corner/original-academy/lesson-imports.ts"
RANGES = ((1, 20), (21, 40), (41, 60), (61, 80))
BOUNDARY_STYLES = ("Heading 1", "Title", "Heading 1", "Heading 1")
BOUNDARY = re.compile(r"^(?:LEZIONE\s+)?(\d{3})(?:\s*\|\s*|\s+)?(.*)$", re.I)


def level_for(number: int) -> str:
    # The first two manuals are A2; volume III closes A2 with lesson 050
    # ("Esame finale A2") and starts the next block at 051. Volume IV says B1.
    return "A2" if number <= 50 else "B1"


def import_volume(file: Path, volume: int) -> tuple[dict, list[dict]]:
    if not file.is_file():
        raise FileNotFoundError(file)
    document = Document(file)
    paragraphs = [
        {"style": p.style.name, "text": p.text}
        for p in document.paragraphs
    ]
    first, last = RANGES[volume - 1]
    boundaries: list[tuple[int, int, str]] = []
    for index, paragraph in enumerate(paragraphs):
        if paragraph["style"] != BOUNDARY_STYLES[volume - 1]:
            continue
        match = BOUNDARY.match(paragraph["text"])
        if match and first <= int(match.group(1)) <= last:
            boundaries.append((index, int(match.group(1)), match.group(2).strip()))
    numbers = [number for _, number, _ in boundaries]
    expected = list(range(first, last + 1))
    if numbers != expected:
        raise ValueError(f"Volume {volume}: expected {expected}, found {numbers}")

    sha256 = hashlib.sha256(file.read_bytes()).hexdigest()
    preface = {"volume": volume, "sourceSha256": sha256, "paragraphs": paragraphs[: boundaries[0][0]]}
    result: list[dict] = []
    for position, (start, number, heading) in enumerate(boundaries):
        end = boundaries[position + 1][0] if position + 1 < len(boundaries) else len(paragraphs)
        original = paragraphs[start:end]
        title = heading or original[1]["text"]
        result.append({
            "id": f"{level_for(number).lower()}-{number:03}",
            "number": number,
            "volume": volume,
            "level": level_for(number),
            "title": title,
            "source": {"file": file.name, "sha256": sha256, "firstParagraph": start, "lastParagraphExclusive": end},
            "paragraphs": original,
        })
    return preface, result


def main() -> None:
    verify = len(sys.argv) > 1 and sys.argv[1] == "--verify"
    args = sys.argv[2:] if verify else sys.argv[1:]
    if len(args) != 4:
        raise SystemExit("Provide all four source .docx files in order.")
    imported = [import_volume(file, volume) for volume, file in enumerate(map(Path, args), 1)]
    lessons = [lesson for _, group in imported for lesson in group]
    if [lesson["number"] for lesson in lessons] != list(range(1, 81)):
        raise ValueError("The imported curriculum must contain exactly 001–080.")
    outputs = {
        ROOT / f"volume-{volume}-preface.json": preface
        for volume, (preface, _) in enumerate(imported, 1)
    }
    outputs.update({LESSONS / f"{lesson['id']}.json": lesson for lesson in lessons})
    outputs[ROOT / "index.json"] = [
        {
            **{key: lesson[key] for key in ("id", "number", "volume", "level", "title")},
            "topics": [
                paragraph["text"]
                for paragraph in lesson["paragraphs"]
                if paragraph["style"] == "Heading 2"
            ],
        }
        for lesson in lessons
    ]
    # Literal dynamic imports allow Next/Vercel to trace every lesson into the
    # deployment while keeping the server bundle for an individual lesson small.
    imports = (
        "// Generated by scripts/import-dolce-lingua.py. Do not edit by hand.\n"
        "export const lessonImporters: Record<string, () => Promise<{ default: unknown }>> = {\n"
        + "".join(
            f'  "{lesson["id"]}": () => import("@/content/italian/original-lessons/lessons/{lesson["id"]}.json"),\n'
            for lesson in lessons
        )
        + "};\n"
    )
    if verify:
        for file, expected in outputs.items():
            if json.loads(file.read_text(encoding="utf-8")) != expected:
                raise ValueError(f"Generated content differs from its Word source: {file}")
        # Prettier may reflow the generated TypeScript without changing the map.
        if "".join(IMPORTS.read_text(encoding="utf-8").split()) != "".join(imports.split()):
            raise ValueError(f"Generated lesson import map differs from the curriculum: {IMPORTS}")
        print(f"Verified {len(lessons)} lessons against all four Word sources.")
    else:
        LESSONS.mkdir(parents=True, exist_ok=True)
        for file, content in outputs.items():
            file.write_text(json.dumps(content, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        IMPORTS.write_text(imports, encoding="utf-8")
        print(f"Imported {len(lessons)} lessons, preserving {sum(len(x['paragraphs']) for x in lessons)} source paragraphs.")


if __name__ == "__main__":
    main()
